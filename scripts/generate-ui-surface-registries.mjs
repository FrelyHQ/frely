import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import {
  formatSourceBlocker,
  loadFrontendBuildContract,
  sourcePrerequisiteBlockers,
} from "./frontend-build-contract-lib.mjs";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const mode = process.argv[2] ?? "verify";
const manifestApp = process.argv[3];
const contractPath = path.join(root, "ops/build/frontend-build-contracts.json");
const contract = JSON.parse(fs.readFileSync(contractPath, "utf8"));
const appNames = contract.apps.map((app) => app.id);
const scopedApp = process.env.FRIDAY_RELAY_UI_SURFACE_SCOPE?.trim() || "";
if (scopedApp && !appNames.includes(scopedApp)) throw new Error(`unknown UI Surface scope: ${scopedApp}`);
const selectedApps = scopedApp ? contract.apps.filter((app) => app.id === scopedApp) : contract.apps;
const generatedRoutes = new Map();
const routeSources = new Map();

const manifestFixture = JSON.parse(fs.readFileSync(
  path.join(root, "scripts", "fixtures", "next-app-paths-manifest.json"),
  "utf8",
));
if (JSON.stringify(routesFromNextManifest(manifestFixture.manifest)) !== JSON.stringify(manifestFixture.expectedUiRoutes)) {
  throw new Error("Next.js app-paths-manifest fixture contract changed");
}

function walk(directory) {
  if (!fs.statSync(directory, { throwIfNoEntry: false })?.isDirectory()) return [];
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      if ([".next", ".output", "dist", "node_modules"].includes(entry.name)) return [];
      return walk(target);
    }
    return [target];
  });
}

function nextRouteFromPage(appRoot, filename) {
  const relative = path.relative(appRoot, path.dirname(filename));
  const segments = relative.split(path.sep).filter((segment) => segment && !segment.startsWith("(") && !segment.startsWith("@"));
  return `/${segments.join("/")}` || "/";
}

export function tanstackRouteFromFile(routesRoot, filename) {
  let relative = path.relative(routesRoot, filename).split(path.sep).join("/");
  relative = relative.replace(/\.(?:lazy\.)?[cm]?[jt]sx?$/u, "");
  if (relative === "__root" || relative.startsWith("-")) return null;
  const segments = splitTanstackFlatRoute(relative);
  const routeSegments = [];
  for (const segment of segments) {
    if (segment === "index" || segment === "route" || segment === "__root") continue;
    if (segment.startsWith("(") && segment.endsWith(")")) continue;
    if (segment.startsWith("_") && !segment.startsWith("$")) continue;
    if (segment.startsWith("-")) return null;
    if (segment === "$") routeSegments.push("[...splat]");
    else if (segment.startsWith("$")) routeSegments.push(`[${segment.slice(1)}]`);
    else routeSegments.push(segment.replace(/\[(.*?)\]/gu, "$1"));
  }
  return `/${routeSegments.join("/")}` || "/";
}

function splitTanstackFlatRoute(relative) {
  const segments = [];
  let segment = "";
  let bracketDepth = 0;
  for (const character of relative) {
    if (character === "[") bracketDepth += 1;
    if (character === "]") bracketDepth = Math.max(0, bracketDepth - 1);
    if (bracketDepth === 0 && (character === "/" || character === ".")) {
      if (segment) segments.push(segment);
      segment = "";
      continue;
    }
    segment += character;
  }
  if (segment) segments.push(segment);
  return segments;
}

function assertTanstackRouteOwnership(routesRoot, pairs, appId) {
  const ownersByRoute = new Map();
  for (const pair of pairs) {
    const owners = ownersByRoute.get(pair.route) ?? [];
    owners.push(pair.file);
    ownersByRoute.set(pair.route, owners);
  }
  for (const [route, owners] of ownersByRoute) {
    if (owners.length === 1) continue;
    const indexOwners = owners.filter((file) => {
      const relative = path.relative(routesRoot, file).split(path.sep).join("/")
        .replace(/\.(?:lazy\.)?[cm]?[jt]sx?$/u, "");
      return relative === "index" || relative.endsWith(".index") || relative.endsWith("/index");
    });
    if (owners.length === 2 && indexOwners.length === 1) continue;
    throw new Error(
      `${appId}: multiple TanStack route modules own ${route}:\n${owners.map((file) => path.relative(root, file)).join("\n")}`,
    );
  }
}

function routeRegistrySource(routes) {
  return [
    "/* Generated by scripts/generate-ui-surface-registries.mjs. Do not edit. */",
    'import { createRouteRegistry } from "@frely/observability/contracts";',
    "",
    `export const routeNames = ${JSON.stringify(routes, null, 2)} as const;`,
    "export const routeRegistry = createRouteRegistry(routeNames);",
    "",
  ].join("\n");
}

function dialogRegistrySource(keys) {
  return [
    "/* Generated by scripts/generate-ui-surface-registries.mjs. Do not edit. */",
    `export const dialogNames = ${JSON.stringify(keys, null, 2)} as const;`,
    "",
  ].join("\n");
}

function dialogKeys() {
  const roots = ["apps/admin", "apps/web", "packages/console-ui", "packages/team-console-ui"].map((value) => path.join(root, value));
  const files = roots.flatMap(walk).filter((file) => file.endsWith(".tsx"));
  const keys = [];
  const missing = [];
  for (const file of files) {
    if (file.endsWith("/packages/console-ui/src/console-dialog.tsx")) continue;
    const source = fs.readFileSync(file, "utf8");
    const localDialogKey = /function Dialog\([^)]*\)[\s\S]*?<UiDialog\s+observabilityKey="([a-z][a-z0-9]*(?:-[a-z0-9]+)*)"/.exec(source)?.[1];
    let localDialogKeyRegistered = false;
    for (const match of source.matchAll(/<(?:Dialog|ConsoleDialog|AdminDialog)\b([\s\S]*?)>/g)) {
      const key = /\bobservabilityKey="([a-z][a-z0-9]*(?:-[a-z0-9]+)*)"/.exec(match[1] ?? "")?.[1];
      if (key) keys.push(key);
      else if (match[0].startsWith("<Dialog") && localDialogKey) {
        if (!localDialogKeyRegistered) keys.push(localDialogKey);
        localDialogKeyRegistered = true;
      } else missing.push(`${path.relative(root, file)}:${source.slice(0, match.index).split("\n").length}`);
    }
  }
  if (missing.length) throw new Error(`Dialog observabilityKey must be a non-empty kebab-case literal:\n${missing.join("\n")}`);
  const duplicates = keys.filter((key, index) => keys.indexOf(key) !== index);
  if (duplicates.length) throw new Error(`Duplicate Dialog observabilityKey: ${[...new Set(duplicates)].join(", ")}`);
  return keys.sort();
}

function assertOrWrite(file, expected) {
  if (mode === "generate") {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, expected);
    return;
  }
  const actual = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (actual !== expected) throw new Error(`${path.relative(root, file)} is stale; run bun run observability:generate`);
}

for (const app of selectedApps) {
  const loaded = loadFrontendBuildContract(contractPath, app.id, root);
  const blockers = sourcePrerequisiteBlockers(loaded.app, root);
  if (blockers.length > 0) {
    throw new Error(`UI Surface generation blocked:\n${blockers.map((entry) => formatSourceBlocker(app.id, entry)).join("\n")}`);
  }
  const sourceRoot = path.join(root, app.surface.sourceRoot);
  let sources;
  let routes;
  if (app.surface.kind === "next-app-router") {
    assertNoRootLoadingBoundary(sourceRoot, app.id);
    sources = walk(sourceRoot).filter((file) => file.endsWith(`${path.sep}page.tsx`));
    routes = sources.map((file) => nextRouteFromPage(sourceRoot, file));
  } else if (app.surface.kind === "tanstack-file-routes") {
    sources = walk(sourceRoot).filter((file) =>
      /\.(?:lazy\.)?[cm]?[jt]sx?$/u.test(file) && !/\.(?:test|spec)\.[^.]+$/u.test(file)
    );
    const pairs = sources
      .map((file) => ({ file, route: tanstackRouteFromFile(sourceRoot, file) }))
      .filter((entry) => entry.route)
      .filter((entry) => !(app.surface.excludePrefixes ?? []).some((prefix) => entry.route.startsWith(prefix)));
    assertTanstackRouteOwnership(sourceRoot, pairs, app.id);
    sources = pairs.map((entry) => entry.file);
    routes = pairs.map((entry) => entry.route);
    const generatedTree = fs.readFileSync(path.join(root, app.surface.generatedRouteTree), "utf8");
    const missingTreeSources = sources.filter((file) => {
      const relative = path.relative(path.dirname(path.join(root, app.surface.generatedRouteTree)), file)
        .split(path.sep).join("/")
        .replace(/\.(?:lazy\.)?[cm]?[jt]sx?$/u, "");
      const specifier = relative.startsWith(".") ? relative : `./${relative}`;
      return !generatedTree.includes(specifier);
    });
    if (missingTreeSources.length > 0) {
      throw new Error(`${app.id} generated route tree is missing UI route modules:\n${missingTreeSources.map((file) => path.relative(root, file)).join("\n")}`);
    }
  } else throw new Error(`${app.id}: unsupported UI Surface kind ${app.surface.kind}`);
  const sorted = [...new Set(routes)].sort();
  if (app.surface.kind === "next-app-router" && sorted.length !== routes.length) {
    throw new Error(`${app.id}: multiple route modules map to the same UI Surface`);
  }
  generatedRoutes.set(app.id, sorted);
  routeSources.set(app.id, sources);
  assertOrWrite(path.join(root, app.surface.registry), routeRegistrySource(sorted));
}

assertOrWrite(
  path.join(root, "packages/observability/src/generated-dialog-registry.ts"),
  dialogRegistrySource(dialogKeys()),
);

if (mode === "verify-manifest") {
  if (!appNames.includes(manifestApp)) throw new Error(`verify-manifest requires app name: ${appNames.join(" or ")}`);
  const app = contract.apps.find((candidate) => candidate.id === manifestApp);
  const manifestFile = path.join(root, app.surface.buildManifest);
  if (!fs.existsSync(manifestFile)) throw new Error(`${path.relative(root, manifestFile)} does not exist`);
  const manifest = JSON.parse(fs.readFileSync(manifestFile, "utf8"));
  if (app.surface.kind === "next-app-router") {
    const manifestRoutes = routesFromNextManifest(manifest);
    const expected = generatedRoutes.get(manifestApp) ?? [];
    if (JSON.stringify(manifestRoutes) !== JSON.stringify(expected)) {
      throw new Error(`${manifestApp} Next.js app-paths-manifest routes differ from the generated route registry`);
    }
  } else {
    const manifestSpecifiers = [
      ...Object.keys(manifest),
      ...Object.values(manifest).flatMap((entry) => [
        entry?.src,
        ...(entry?.imports ?? []),
        ...(entry?.dynamicImports ?? []),
      ]),
    ].filter((value) => typeof value === "string")
      .map((value) => value.split("?")[0].split(path.sep).join("/"));
    const missing = (routeSources.get(manifestApp) ?? [])
      .filter(routeRequiresClientChunk)
      .filter((file) => {
        const relative = path.relative(root, file).split(path.sep).join("/");
        const appRelative = path.relative(path.join(root, app.root), file).split(path.sep).join("/");
        return !manifestSpecifiers.some((key) =>
          key === relative || key.endsWith(`/${relative}`) || key === appRelative || key.endsWith(`/${appRelative}`)
        );
      });
    if (missing.length > 0) {
      throw new Error(`${manifestApp} Vite manifest is missing route chunks:\n${missing.map((file) => path.relative(root, file)).join("\n")}`);
    }
  }
}

console.log(`UI Surface registries ${mode === "generate" ? "generated" : "verified"}.`);

function routeRequiresClientChunk(file) {
  return /\bcomponent\s*:/u.test(fs.readFileSync(file, "utf8"));
}

function assertNoRootLoadingBoundary(appRoot, appName) {
  const rootLoading = path.join(appRoot, "loading.tsx");
  if (fs.existsSync(rootLoading)) {
    throw new Error(`${appName} root loading.tsx replaces the mounted console shell during slow navigation; keep the current route visible until the destination is ready`);
  }
}

function routesFromNextManifest(manifest) {
  return Object.keys(manifest)
    .filter((key) => key === "/page" || key.endsWith("/page"))
    .map((key) => key === "/page" ? "/" : key.slice(0, -"/page".length))
    .filter((route) => !route.startsWith("/_"))
    .sort();
}
